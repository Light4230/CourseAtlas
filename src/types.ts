export interface Course {
  id: string;
  name: string;
  color: string;
  createdAt: string;
  updatedAt: string;
  documentCount: number;
  lectureCount: number;
  topicCount: number;
  lastActivityAt: string | null;
}

export type DocumentStatus = 'queued' | 'parsing' | 'outlining' | 'ready' | 'failed';

export interface DocumentDto {
  id: string;
  courseId: string;
  filename: string;
  storedPath: string;
  mimeType: string;
  sizeBytes: number;
  pageCount: number | null;
  status: DocumentStatus;
  errorCode: string | null;
  errorMessage: string | null;
  warningCode: string | null;
  warningPages: number[];
  outlineModelId: string | null;
  outlineModelName: string | null;
  uploadedAt: string;
  updatedAt: string;
}

export interface SourceRef {
  documentId: string;
  filename: string;
  page: number;
  quote: string;
}

export type TopicKind = 'chapter' | 'section' | 'point';

export interface Topic {
  id: string;
  courseId: string;
  lectureId: string;
  parentId: string | null;
  number: string;
  title: string;
  summary: string;
  summaryEn: string;
  summaryZh: string;
  kind: TopicKind;
  level: number;
  keywords: string[];
  sourceRefs: SourceRef[];
  autoGenerated: boolean;
  manuallyEdited: boolean;
  sortOrder: number;
}

export interface Lecture {
  id: string;
  courseId: string;
  documentId: string;
  order: number;
  title: string;
  generationMethod: 'ai' | 'headings' | 'pages';
  outlineModelName: string | null;
  outlineWarning: string | null;
  autoGenerated: boolean;
  document: {
    id: string;
    filename: string;
    pageCount: number | null;
    status: DocumentStatus;
    errorCode: string | null;
    warningCode: string | null;
    warningPages: number[];
  };
  topics: Topic[];
}

export interface Outline {
  course: Course;
  documents: DocumentDto[];
  lectures: Lecture[];
}

export type SourceType = 'course_material' | 'model_knowledge' | 'web' | 'mixed';

export interface RetrievalChunk {
  chunkId: string;
  documentId: string;
  lectureId: string;
  filename: string;
  lectureTitle: string;
  page: number;
  text: string;
  quote: string;
  score: number;
}

export interface SearchResult {
  title: string;
  url: string;
  snippet: string;
}

export interface ToolTrace {
  name: string;
  arguments: Record<string, unknown>;
  ok: boolean;
  summary: string;
}

export interface RetrievalTrace {
  topK: number;
  returned: number;
  queryTerms: string[];
  matchedTerms: string[];
  coverage: number;
  bestScore: number;
  confidence: number;
  threshold: number;
  fallbackReason:
    | 'below_threshold'
    | 'no_results'
    | 'model_fallback_disabled'
    | 'search_unavailable'
    | 'search_no_results'
    | 'search_error'
    | null;
  searchConfigured: boolean;
  searchAttempted: boolean;
  searchResultCount: number;
  searchErrorCode?: string;
  tools?: ToolTrace[];
}

export interface ChatMessage {
  id: string;
  courseId: string;
  question: string;
  answer: string;
  sourceType: SourceType;
  modelDisplayName: string;
  modelId: string | null;
  retrievedChunks: RetrievalChunk[];
  searchResults: SearchResult[];
  confidence: number;
  trace: RetrievalTrace;
  feedback: 'up' | 'down' | null;
  createdAt: string;
}

export interface ModelConfig {
  id: string;
  displayName: string;
  provider: 'deepseek' | 'openai-compatible';
  baseUrl: string;
  modelId: string;
  maskedKey: string;
}

export interface AppSettings {
  highThreshold: number;
  allowModelFallback: boolean;
  enableWebSearch: boolean;
  updatedAt: string;
  searchConfigured: boolean;
  searchProvider: string | null;
}

export interface AppConfig {
  searchConfigured: boolean;
  searchProvider: string | null;
  allowLocalModels: boolean;
  maxUploadMb: number;
}

export interface PageText {
  documentId: string;
  filename: string;
  page: number;
  text: string;
}

export interface UploadingFile {
  id: string;
  filename: string;
  progress: number;
  status: 'uploading' | 'failed' | 'rejected';
  errorCode: string | null;
}
