interface LectureRow {
  id: string;
  course_id: string;
  document_id: string;
  sort_order: number;
  title: string;
  generation_method: string;
  outline_model_name: string | null;
  outline_warning: string | null;
  auto_generated: number;
}

export interface AiOutlineContext {
  model: ModelWithSecret;
  keyStore: KeyStore;
}

export function getOutline(
  db: DatabaseSync,
  courseId: string,
): {
  course: ReturnType<typeof getCourse>;
  documents: ReturnType<typeof mapDocument>[];
  lectures: OutlineLecture[];
} {
  const course = getCourse(db, courseId);
  const documents = db
    .prepare('SELECT * FROM documents WHERE course_id = ? ORDER BY uploaded_at ASC')
    .all(courseId) as Array<Record<string, unknown>>;
  const lectures = db
    .prepare('SELECT * FROM lectures WHERE course_id = ? ORDER BY sort_order ASC')
    .all(courseId) as unknown as LectureRow[];
  const topics = db
    .prepare('SELECT * FROM topics WHERE course_id = ? ORDER BY sort_order ASC, created_at ASC')
    .all(courseId) as Array<Record<string, unknown>>;
  const documentById = new Map(documents.map((row) => [String(row.id), row]));

  const mappedLectures: OutlineLecture[] = lectures.map((lecture) => {
    const document = documentById.get(lecture.document_id);
    return {
      id: lecture.id,
      courseId: lecture.course_id,
      documentId: lecture.document_id,
      order: Number(lecture.sort_order),
      title: lecture.title,
      generationMethod: normalizeGenerationMethod(lecture.generation_method),
      outlineModelName: lecture.outline_model_name ?? null,
      outlineWarning: lecture.outline_warning ?? null,
      autoGenerated: Number(lecture.auto_generated) === 1,
      document: {
        id: lecture.document_id,
        filename: document ? String(document.filename) : 'Unknown file',
        pageCount:
          document?.page_count === null || document?.page_count === undefined
            ? null
            : Number(document.page_count),
        status: document ? (String(document.status) as OutlineLecture['document']['status']) : 'failed',
        errorCode: document?.error_code ? String(document.error_code) : null,
        warningCode: document?.warning_code ? String(document.warning_code) : null,
        warningPages: parseNumberArray(document?.warning_pages),
      },
      topics: topics.filter((topic) => String(topic.lecture_id) === lecture.id).map(mapTopic),
    };
  });

  return {
    course,
    documents: documents.map(mapDocument),
    lectures: mappedLectures,
  };
}

export function getTopic(db: DatabaseSync, topicId: string): OutlineTopic {
  const row = db.prepare('SELECT * FROM topics WHERE id = ?').get(topicId) as
    | Record<string, unknown>
    | undefined;
  if (!row) throw new ApiError(404, 'TOPIC_NOT_FOUND', 'Topic not found.');
  return mapTopic(row);
}

export function updateTopic(
  db: DatabaseSync,
  topicId: string,
  input: {
    title?: string;
    summary?: string;
    summaryEn?: string;
    summaryZh?: string;
    keywords?: string[];
  },
): OutlineTopic {
  const topic = getTopic(db, topicId);
  const title = input.title?.trim() || topic.title;
  const summaryEn = (input.summaryEn ?? input.summary ?? topic.summaryEn).trim();
  const summaryZh = (input.summaryZh ?? topic.summaryZh).trim();
  const summary = summaryEn || topic.summary;
  const keywords = input.keywords ?? topic.keywords;
  db.prepare(
    `UPDATE topics
       SET title = ?, summary = ?, summary_en = ?, summary_zh = ?, keywords = ?,
           manually_edited = 1, auto_generated = 0, updated_at = ?
     WHERE id = ?`,
  ).run(title, summary, summaryEn, summaryZh, JSON.stringify(keywords), nowIso(), topicId);
  touchCourse(db, topic.courseId);
  return getTopic(db, topicId);
}

export function mergeWithNext(
  db: DatabaseSync,
  topicId: string,
  input: { title?: string },
): OutlineTopic {
  const current = getTopic(db, topicId);
  if (current.kind !== 'point') {
    throw new ApiError(409, 'CANNOT_MERGE', 'Only knowledge points can be merged.');
  }
  const siblings = db
    .prepare('SELECT * FROM topics WHERE lecture_id = ? ORDER BY sort_order ASC')
    .all(current.lectureId) as Array<Record<string, unknown>>;
  const nextRow = siblings
    .map(mapTopic)
    .find(
      (topic) =>
        topic.parentId === current.parentId && topic.sortOrder > current.sortOrder,
    );
  if (!nextRow) {
    throw new ApiError(409, 'CANNOT_MERGE', 'There is no following topic to merge.');
  }
  const next = nextRow;
  const sourceRefs = dedupeRefs([...current.sourceRefs, ...next.sourceRefs]);
  const keywords = [...new Set([...current.keywords, ...next.keywords])].slice(0, 10);
  const summaryEn = [current.summaryEn, next.summaryEn].filter(Boolean).join(' ').slice(0, 800);
  const summaryZh = [current.summaryZh, next.summaryZh].filter(Boolean).join(' ').slice(0, 800);
  const title = input.title?.trim() || `${current.title} / ${next.title}`;
  db.exec('BEGIN');
  try {
    db.prepare(
      `UPDATE topics SET title = ?, summary = ?, summary_en = ?, summary_zh = ?, keywords = ?,
         source_refs = ?, manually_edited = 1, auto_generated = 0, updated_at = ? WHERE id = ?`,
    ).run(
      title,
      summaryEn,
      summaryEn,
      summaryZh,
      JSON.stringify(keywords),
      JSON.stringify(sourceRefs),
      nowIso(),
      current.id,
    );
    db.prepare('DELETE FROM topics WHERE id = ?').run(next.id);
    renumberTopics(db, current.lectureId);
    db.exec('COMMIT');
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
  touchCourse(db, current.courseId);
  return getTopic(db, current.id);
}

export function splitTopic(
  db: DatabaseSync,
  topicId: string,
  input: { title: string; keptSourceRefs: number },
): { original: OutlineTopic; created: OutlineTopic } {
  const topic = getTopic(db, topicId);
  if (topic.kind !== 'point') {
    throw new ApiError(409, 'CANNOT_SPLIT', 'Only knowledge points can be split.');
  }
  if (topic.sourceRefs.length < 2) {
    throw new ApiError(409, 'CANNOT_SPLIT', 'This topic has fewer than two source excerpts.');
  }
  const kept = Math.trunc(input.keptSourceRefs);
  if (!Number.isFinite(kept) || kept < 1 || kept >= topic.sourceRefs.length) {
    throw new ApiError(409, 'CANNOT_SPLIT', 'Choose a valid split point between source excerpts.');
  }
  const originalRefs = topic.sourceRefs.slice(0, kept);
  const newRefs = topic.sourceRefs.slice(kept);
  const newId = crypto.randomUUID();
  const summaryEn = makeExcerpt(newRefs[0]?.quote ?? '', 260);
  const keywords = extractKeywords(`${input.title} ${newRefs.map((ref) => ref.quote).join(' ')}`);
  db.exec('BEGIN');
  try {
    db.prepare(
      `UPDATE topics SET source_refs = ?, manually_edited = 1, auto_generated = 0, updated_at = ? WHERE id = ?`,
    ).run(JSON.stringify(originalRefs), nowIso(), topic.id);
    db.prepare(
      `UPDATE topics SET sort_order = sort_order + 1
        WHERE lecture_id = ? AND parent_id IS ? AND sort_order > ?`,
    ).run(topic.lectureId, topic.parentId, topic.sortOrder);
    db.prepare(
      `INSERT INTO topics
        (id, course_id, lecture_id, parent_id, number, title, summary, summary_en, summary_zh,
         kind, level, keywords, source_refs, auto_generated, manually_edited, sort_order, created_at, updated_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'point', ?, ?, ?, 0, 1, ?, ?, ?)`,
    ).run(
      newId,
      topic.courseId,
      topic.lectureId,
      topic.parentId,
      `${topic.number}.1`,
      input.title.trim(),
      summaryEn,
      summaryEn,
      '',
      topic.level,
      JSON.stringify(keywords),
      JSON.stringify(newRefs),
      topic.sortOrder + 1,
      nowIso(),
      nowIso(),
    );
    renumberTopics(db, topic.lectureId);
    db.exec('COMMIT');
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
  touchCourse(db, topic.courseId);
  return { original: getTopic(db, topic.id), created: getTopic(db, newId) };
}

export async function storeExtractedContent(
  db: DatabaseSync,
  documentId: string,
  pages: ExtractedPage[],
  pageCount: number,
  emptyPages: number[],
  ai?: AiOutlineContext,
): Promise<{ topicCount: number; method: 'ai' | 'headings' | 'pages' }> {
  const document = getDocument(db, documentId);
  const lecture = db
    .prepare('SELECT * FROM lectures WHERE document_id = ?')
    .get(documentId) as LectureRow | undefined;
  if (!lecture) throw new ApiError(404, 'LECTURE_NOT_FOUND', 'Lecture not found.');

  let aiOutline: AiOutlineChapter[] | null = null;
  let outlineWarning: string | null = null;
  if (ai) {
    try {
      aiOutline = (
        await generateAiOutline(
          pages,
          document.id,
          document.filename,
          ai.model,
          ai.keyStore,
        )
      ).chapters;
    } catch (error) {
      outlineWarning = 'AI_OUTLINE_FAILED';
      console.error(
        '[courseatlas] AI outline failed; using local fallback:',
        error instanceof Error ? error.message : 'unknown error',
      );
    }
  }

  let generated: { method: 'headings' | 'pages'; topics: GeneratedTopic[] } | null = null;
  if (!aiOutline) {
    const previousRows = db
      .prepare('SELECT * FROM topics WHERE lecture_id = ? AND manually_edited = 1 ORDER BY sort_order ASC')
      .all(lecture.id) as Array<Record<string, unknown>>;
    const previousManualTopics = manualTopics(previousRows);
    generated = localOutline(document, lecture, pages, previousManualTopics);
  }

  const chunks = chunkPages(pages);
  const timestamp = nowIso();
  db.exec('BEGIN');
  try {
    db.prepare('DELETE FROM chunks WHERE document_id = ?').run(documentId);
    db.prepare('DELETE FROM topics WHERE lecture_id = ?').run(lecture.id);
    for (const chunk of chunks) {
      db.prepare(
        `INSERT INTO chunks (id, course_id, document_id, lecture_id, page, chunk_index, text, created_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
      ).run(
        crypto.randomUUID(),
        lecture.course_id,
        documentId,
        lecture.id,
        chunk.page,
        chunk.chunkIndex,
        chunk.text,
        timestamp,
      );
    }

    if (aiOutline) {
      insertAiTopics(db, lecture, aiOutline);
      updateLectureOutlineMeta(db, lecture.id, 'ai', ai?.model.displayName ?? null, null);
    } else if (generated) {
      insertFlatTopics(db, lecture, generated.topics, generated.method);
      updateLectureOutlineMeta(
        db,
        lecture.id,
        generated.method,
        null,
        outlineWarning,
      );
    }

    db.prepare(
      `UPDATE documents SET status = 'ready', error_code = NULL, error_message = NULL,
         page_count = ?, warning_code = ?, warning_pages = ?, updated_at = ? WHERE id = ?`,
    ).run(
      pageCount,
      emptyPages.length > 0 ? 'SOME_PAGES_NO_TEXT' : null,
      JSON.stringify(emptyPages),
      timestamp,
      documentId,
    );
    db.exec('COMMIT');
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
  touchCourse(db, lecture.course_id);
  return {
    topicCount: countTopics(db, lecture.id),
    method: aiOutline ? 'ai' : (generated?.method ?? 'pages'),
  };
}

export function clearDocumentContent(db: DatabaseSync, documentId: string): void {
  const lecture = db
    .prepare('SELECT id FROM lectures WHERE document_id = ?')
    .get(documentId) as { id: string } | undefined;
  if (!lecture) return;
  db.prepare('DELETE FROM chunks WHERE document_id = ?').run(documentId);
  db.prepare('DELETE FROM topics WHERE lecture_id = ?').run(lecture.id);
}

export async function regenerateLectureOutline(
  db: DatabaseSync,
  uploadsDir: string,
  lectureId: string,
  options: {
    mode: 'ai' | 'local';
    preserveManualEdits: boolean;
    ai?: AiOutlineContext;
  },
): Promise<OutlineLecture | null> {
  const lecture = db.prepare('SELECT * FROM lectures WHERE id = ?').get(lectureId) as
    | LectureRow
    | undefined;
  if (!lecture) throw new ApiError(404, 'LECTURE_NOT_FOUND', 'Lecture not found.');
  const document = getDocument(db, lecture.document_id);
  const extracted = await extractPdf(path.resolve(uploadsDir, document.storedPath));

  if (options.mode === 'ai') {
    if (!options.ai) {
      throw new ApiError(400, 'MODEL_REQUIRED', 'Select a model to generate an AI outline.');
    }
    // Do not delete the existing outline until the AI call succeeds.
    const aiOutline = (
      await generateAiOutline(
        extracted.pages,
        document.id,
        document.filename,
        options.ai.model,
        options.ai.keyStore,
      )
    ).chapters;
    const timestamp = nowIso();
    db.exec('BEGIN');
    try {
      db.prepare('DELETE FROM topics WHERE lecture_id = ?').run(lectureId);
      insertAiTopics(db, lecture, aiOutline);
      updateLectureOutlineMeta(db, lectureId, 'ai', options.ai.model.displayName, null);
      updateDocumentAfterOutline(db, document.id, extracted.pageCount, extracted.emptyPages);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
    touchCourse(db, lecture.course_id);
    return findLecture(db, lecture.course_id, lectureId);
  }

  const previousRows = db
    .prepare('SELECT * FROM topics WHERE lecture_id = ? AND manually_edited = 1 ORDER BY sort_order ASC')
    .all(lectureId) as Array<Record<string, unknown>>;
  const generated = localOutline(
    document,
    lecture,
    extracted.pages,
    options.preserveManualEdits ? manualTopics(previousRows) : [],
  );
  const timestamp = nowIso();
  db.exec('BEGIN');
  try {
    db.prepare('DELETE FROM topics WHERE lecture_id = ?').run(lectureId);
    insertFlatTopics(db, lecture, generated.topics, generated.method);
    updateLectureOutlineMeta(db, lectureId, generated.method, null, null);
    updateDocumentAfterOutline(db, document.id, extracted.pageCount, extracted.emptyPages);
    db.exec('COMMIT');
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }
  touchCourse(db, lecture.course_id);
  return findLecture(db, lecture.course_id, lectureId);
}

function localOutline(
  document: { id: string; filename: string },
  lecture: LectureRow,
  pages: ExtractedPage[],
  previousManualTopics: PreviousManualTopic[],
): { method: 'headings' | 'pages'; topics: GeneratedTopic[] } {
  try {
    return generateOutline(
      pages,
      document.id,
      document.filename,
      Number(lecture.sort_order),
      previousManualTopics,
    );
  } catch (error) {
    console.error('[courseatlas] local outline generation failed; using page fallback:', error);
    return { method: 'pages', topics: emergencyPageOutline(document, pages) };
  }
}

function insertAiTopics(
  db: DatabaseSync,
  lecture: LectureRow,
  chapters: AiOutlineChapter[],
): void {
  const timestamp = nowIso();
  chapters.forEach((chapter, chapterIndex) => {
    const chapterId = crypto.randomUUID();
    insertTopicRow(db, {
      id: chapterId,
      lecture,
      parentId: null,
      number: `${chapterIndex + 1}`,
      title: chapter.title,
      summaryEn: chapter.summaryEn,
      summaryZh: chapter.summaryZh,
      kind: 'chapter',
      level: 0,
      keywords: chapter.keywords,
      sourceRefs: chapter.sourceRefs,
      sortOrder: chapterIndex,
      timestamp,
    });
    chapter.sections.forEach((section, sectionIndex) => {
      const sectionId = crypto.randomUUID();
      insertTopicRow(db, {
        id: sectionId,
        lecture,
        parentId: chapterId,
        number: `${chapterIndex + 1}.${sectionIndex + 1}`,
        title: section.title,
        summaryEn: section.summaryEn,
        summaryZh: section.summaryZh,
        kind: 'section',
        level: 1,
        keywords: section.keywords,
        sourceRefs: section.sourceRefs,
        sortOrder: sectionIndex,
        timestamp,
      });
      section.points.forEach((point, pointIndex) => {
        insertTopicRow(db, {
          id: crypto.randomUUID(),
          lecture,
          parentId: sectionId,
          number: `${chapterIndex + 1}.${sectionIndex + 1}.${pointIndex + 1}`,
          title: point.title,
          summaryEn: point.summaryEn,
          summaryZh: point.summaryZh,
          kind: 'point',
          level: 2,
          keywords: point.keywords,
          sourceRefs: point.sourceRefs,
          sortOrder: pointIndex,
          timestamp,
        });
      });
    });
  });
  renumberTopics(db, lecture.id);
}

function insertFlatTopics(
  db: DatabaseSync,
  lecture: LectureRow,
  topics: GeneratedTopic[],
  method: 'headings' | 'pages',
): void {
  const timestamp = nowIso();
  topics.forEach((topic, index) => {
    insertTopicRow(db, {
      id: crypto.randomUUID(),
      lecture,
      parentId: null,
      number: `${lecture.sort_order}.${index + 1}`,
      title: topic.title,
      summaryEn: topic.summary,
      summaryZh: '',
      kind: 'point',
      level: 0,
      keywords: topic.keywords,
      sourceRefs: topic.sourceRefs,
      sortOrder: index,
      timestamp,
    });
  });
  updateLectureOutlineMeta(db, lecture.id, method, null, null);
}

function insertTopicRow(
  db: DatabaseSync,
  input: {
    id: string;
    lecture: LectureRow;
    parentId: string | null;
    number: string;
    title: string;
    summaryEn: string;
    summaryZh: string;
    kind: TopicKind;
    level: number;
    keywords: string[];
    sourceRefs: SourceRef[];
    sortOrder: number;
    timestamp: string;
  },
): void {
  db.prepare(
    `INSERT INTO topics
      (id, course_id, lecture_id, parent_id, number, title, summary, summary_en, summary_zh,
       kind, level, keywords, source_refs, auto_generated, manually_edited, sort_order, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, 0, ?, ?, ?)`,
  ).run(
    input.id,
    input.lecture.course_id,
    input.lecture.id,
    input.parentId,
    input.number,
    input.title,
    input.summaryEn,
    input.summaryEn,
    input.summaryZh,
    input.kind,
    input.level,
    JSON.stringify(input.keywords),
    JSON.stringify(input.sourceRefs),
    input.sortOrder,
    input.timestamp,
    input.timestamp,
  );
}

function updateLectureOutlineMeta(
  db: DatabaseSync,
  lectureId: string,
  method: 'ai' | 'headings' | 'pages',
  modelName: string | null,
  warning: string | null,
): void {
  db.prepare(
    `UPDATE lectures SET generation_method = ?, outline_model_name = ?, outline_warning = ?,
       auto_generated = 1, updated_at = ? WHERE id = ?`,
  ).run(method, modelName, warning, nowIso(), lectureId);
}

function updateDocumentAfterOutline(
  db: DatabaseSync,
  documentId: string,
  pageCount: number,
  emptyPages: number[],
): void {
  db.prepare(
    `UPDATE documents SET status = 'ready', error_code = NULL, error_message = NULL,
       page_count = ?, warning_code = ?, warning_pages = ?, updated_at = ? WHERE id = ?`,
  ).run(
    pageCount,
    emptyPages.length > 0 ? 'SOME_PAGES_NO_TEXT' : null,
    JSON.stringify(emptyPages),
    nowIso(),
    documentId,
  );
}

function findLecture(
  db: DatabaseSync,
  courseId: string,
  lectureId: string,
): OutlineLecture | null {
  return getOutline(db, courseId).lectures.find((lecture) => lecture.id === lectureId) ?? null;
}

function countTopics(db: DatabaseSync, lectureId: string): number {
  const row = db
    .prepare('SELECT COUNT(*) AS count FROM topics WHERE lecture_id = ?')
    .get(lectureId) as { count: number };
  return Number(row.count);
}

function manualTopics(rows: Array<Record<string, unknown>>): PreviousManualTopic[] {
  return rows
    .map(mapTopic)
    .map((topic) => ({
      title: topic.title,
      summary: topic.summaryEn || topic.summary,
      keywords: topic.keywords,
      page: topic.sourceRefs[0]?.page ?? 0,
    }))
    .filter((topic) => topic.page > 0);
}

function renumberTopics(db: DatabaseSync, lectureId: string): void {
  const lecture = db.prepare('SELECT sort_order FROM lectures WHERE id = ?').get(lectureId) as {
    sort_order: number;
  };
  const rows = (
    db
      .prepare('SELECT * FROM topics WHERE lecture_id = ? ORDER BY sort_order ASC, created_at ASC')
      .all(lectureId) as Array<Record<string, unknown>>
  ).map(mapTopic);
  const children = new Map<string | null, OutlineTopic[]>();
  for (const topic of rows) {
    const list = children.get(topic.parentId) ?? [];
    list.push(topic);
    children.set(topic.parentId, list);
  }
  for (const list of children.values()) {
    list.sort((a, b) => a.sortOrder - b.sortOrder);
  }
  const roots = children.get(null) ?? [];
  const hasChapters = roots.some((topic) => topic.kind === 'chapter');

  roots.forEach((root, rootIndex) => {
    root.sortOrder = rootIndex;
    if (hasChapters) {
      root.number = `${rootIndex + 1}`;
      const sections = (children.get(root.id) ?? []).sort((a, b) => a.sortOrder - b.sortOrder);
      sections.forEach((section, sectionIndex) => {
        section.sortOrder = sectionIndex;
        section.number = `${root.number}.${sectionIndex + 1}`;
        const points = (children.get(section.id) ?? []).sort((a, b) => a.sortOrder - b.sortOrder);
        points.forEach((point, pointIndex) => {
          point.sortOrder = pointIndex;
          point.number = `${section.number}.${pointIndex + 1}`;
          updateTopicNumber(db, point);
        });
        updateTopicNumber(db, section);
      });
      updateTopicNumber(db, root);
    } else {
      // Legacy flat lectures keep the existing lecture-scoped numbering style.
      root.number = `${lecture.sort_order}.${rootIndex + 1}`;
      updateTopicNumber(db, root);
    }
  });
}

function updateTopicNumber(db: DatabaseSync, topic: OutlineTopic): void {
  db.prepare('UPDATE topics SET number = ?, sort_order = ? WHERE id = ?').run(
    topic.number,
    topic.sortOrder,
    topic.id,
  );
}

function emergencyPageOutline(
  document: { id: string; filename: string },
  pages: ExtractedPage[],
): GeneratedTopic[] {
  return pages
    .filter((page) => page.text.trim().length > 0)
    .slice(0, 40)
    .map((page, index) => ({
      title: `Page ${page.page}`,
      summary: makeExcerpt(page.text, 240),
      keywords: extractKeywords(page.text),
      sourceRefs: [
        {
          documentId: document.id,
          filename: document.filename,
          page: page.page,
          quote: makeExcerpt(page.text, 280),
        },
      ],
      autoGenerated: true,
      manuallyEdited: false,
      sortOrder: index,
    }));
}

function mapTopic(row: Record<string, unknown>): OutlineTopic {
  const kind = String(row.kind ?? 'point') as TopicKind;
  const level = Number(row.level ?? (kind === 'chapter' ? 0 : kind === 'section' ? 1 : 2));
  const legacySummary = String(row.summary ?? '');
  const summaryEn = String(row.summary_en ?? legacySummary);
  return {
    id: String(row.id),
    courseId: String(row.course_id),
    lectureId: String(row.lecture_id),
    parentId: row.parent_id ? String(row.parent_id) : null,
    number: String(row.number),
    title: String(row.title),
    summary: summaryEn,
    summaryEn,
    summaryZh: String(row.summary_zh ?? ''),
    kind,
    level,
    keywords: parseStringArray(row.keywords),
    sourceRefs: parseSourceRefs(row.source_refs),
    autoGenerated: Number(row.auto_generated) === 1,
    manuallyEdited: Number(row.manually_edited) === 1,
    sortOrder: Number(row.sort_order),
  };
}

function parseStringArray(value: unknown): string[] {
  try {
    const parsed = JSON.parse(String(value ?? '[]'));
    return Array.isArray(parsed) ? parsed.map(String) : [];
  } catch {
    return [];
  }
}

function parseSourceRefs(value: unknown): SourceRef[] {
  try {
    const parsed = JSON.parse(String(value ?? '[]'));
    if (!Array.isArray(parsed)) return [];
    return parsed
      .filter((item) => item && typeof item === 'object')
      .map((item) => ({
        documentId: String((item as Record<string, unknown>).documentId ?? ''),
        filename: String((item as Record<string, unknown>).filename ?? ''),
        page: Number((item as Record<string, unknown>).page ?? 0),
        quote: String((item as Record<string, unknown>).quote ?? ''),
      }))
      .filter((item) => item.page > 0);
  } catch {
    return [];
  }
}

function parseNumberArray(value: unknown): number[] {
  try {
    const parsed = JSON.parse(String(value ?? '[]'));
    return Array.isArray(parsed) ? parsed.map(Number).filter(Number.isFinite) : [];
  } catch {
    return [];
  }
}

function dedupeRefs(refs: SourceRef[]): SourceRef[] {
  const seen = new Set<string>();
  return refs.filter((ref) => {
    const key = `${ref.documentId}|${ref.page}|${ref.quote}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function normalizeGenerationMethod(value: string): 'ai' | 'headings' | 'pages' {
  if (value === 'ai' || value === 'headings') return value;
  return 'pages';
}
