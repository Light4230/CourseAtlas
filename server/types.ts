export const DOCUMENT_STATUSES = [
  'queued',
  'parsing',
  'outlining',
  'ready',
  'failed',
] as const;
export type DocumentStatus = (typeof DOCUMENT_STATUSES)[number];

export const SOURCE_TYPES = [
  'course_material',
  'model_knowledge',
  'web',
  'mixed',
] as const;
export type SourceType = (typeof SOURCE_TYPES)[number];

export interface SourceRef {
  documentId: string;
  filename: string;
  page: number;
  quote: string;
}

export interface SearchResult {
  title: string;
  url: string;
  snippet: string;
}

export interface RetrievalChunk {
  chunkId: string;
  documentId: string;
  lectureId: string;
  filename: string;
  lectureTitle: string;
  page: number;
  text: string;
  quote: string;
  score: number;
}

export interface ToolTrace {
  name: string;
  arguments: Record<string, unknown>;
  ok: boolean;
  summary: string;
}

export interface RetrievalTrace {
  topK: number;
  returned: number;
  queryTerms: string[];
  matchedTerms: string[];
  coverage: number;
  bestScore: number;
  confidence: number;
  threshold: number;
  fallbackReason:
    | 'below_threshold'
    | 'no_results'
    | 'model_fallback_disabled'
    | 'search_unavailable'
    | 'search_no_results'
    | 'search_error'
    | null;
  searchConfigured: boolean;
  searchAttempted: boolean;
  searchResultCount: number;
  searchErrorCode?: string;
  tools?: ToolTrace[];
}

export interface ChatMessageRow {
  id: string;
  course_id: string;
  question: string;
  answer: string;
  source_type: SourceType;
  model_display_name: string;
  model_id: string | null;
  retrieved_chunks: string;
  search_results: string;
  confidence: number;
  retrieval_trace: string;
  feedback: 'up' | 'down' | null;
  created_at: string;
}

export type TopicKind = 'chapter' | 'section' | 'point';

export interface OutlineTopic {
  id: string;
  courseId: string;
  lectureId: string;
  parentId: string | null;
  number: string;
  title: string;
  summary: string;
  summaryEn: string;
  summaryZh: string;
  kind: TopicKind;
  level: number;
  keywords: string[];
  sourceRefs: SourceRef[];
  autoGenerated: boolean;
  manuallyEdited: boolean;
  sortOrder: number;
}

export interface OutlineLecture {
  id: string;
  courseId: string;
  documentId: string;
  order: number;
  title: string;
  generationMethod: 'ai' | 'headings' | 'pages';
  outlineModelName: string | null;
  outlineWarning: string | null;
  autoGenerated: boolean;
  document: {
    id: string;
    filename: string;
    pageCount: number | null;
    status: DocumentStatus;
    errorCode: string | null;
    warningCode: string | null;
    warningPages: number[];
  };
  topics: OutlineTopic[];
}
