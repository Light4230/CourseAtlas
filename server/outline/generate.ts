import type { SourceRef } from '../types.js';
import type { ExtractedPage } from '../pdf/extract.js';
import { makeExcerpt } from '../pdf/chunk.js';

export interface GeneratedTopic {
  title: string;
  summary: string;
  keywords: string[];
  sourceRefs: SourceRef[];
  autoGenerated: boolean;
  manuallyEdited: boolean;
  sortOrder: number;
}

export interface PreviousManualTopic {
  title: string;
  summary: string;
  keywords: string[];
  page: number;
}

export interface GeneratedOutline {
  method: 'headings' | 'pages';
  topics: GeneratedTopic[];
}

interface HeadingPosition {
  pageIndex: number;
  lineIndex: number;
  lineSpan: number;
  page: number;
  title: string;
}

const STOP_WORDS = new Set([
  'a', 'about', 'above', 'after', 'again', 'against', 'all', 'also', 'am', 'an', 'and', 'any',
  'are', 'as', 'at', 'be', 'because', 'been', 'before', 'being', 'below', 'between', 'both',
  'but', 'by', 'can', 'could', 'did', 'do', 'does', 'doing', 'down', 'during', 'each', 'few',
  'for', 'from', 'further', 'had', 'has', 'have', 'having', 'he', 'her', 'here', 'hers',
  'herself', 'him', 'himself', 'his', 'how', 'i', 'if', 'in', 'into', 'is', 'it', 'its',
  'itself', 'just', 'me', 'more', 'most', 'my', 'myself', 'no', 'nor', 'not', 'now', 'of',
  'off', 'on', 'once', 'only', 'or', 'other', 'our', 'ours', 'ourselves', 'out', 'over', 'own',
  'same', 'she', 'should', 'so', 'some', 'such', 'than', 'that', 'the', 'their', 'theirs',
  'them', 'themselves', 'then', 'there', 'these', 'they', 'this', 'those', 'through', 'to',
  'too', 'under', 'until', 'up', 'very', 'was', 'we', 'were', 'what', 'when', 'where', 'which',
  'while', 'who', 'whom', 'why', 'will', 'with', 'would', 'you', 'your', 'yours', 'yourself',
  'yourselves', 'using', 'used', 'use', 'page', 'lecture', 'slide', 'slides', 'example',
]);

export function generateOutline(
  pages: ExtractedPage[],
  documentId: string,
  filename: string,
  lectureOrder: number,
  previousManualTopics: PreviousManualTopic[] = [],
): GeneratedOutline {
  const numbered = findNumberedHeadings(pages);
  const fontHeadings = findFontHeadings(pages);
  const headings =
    fontHeadings.length >= 2 && (fontHeadings.length >= numbered.length || numbered.length < 2)
      ? fontHeadings
      : numbered;
  const method: 'headings' | 'pages' = headings.length >= 2 ? 'headings' : 'pages';
  const draft =
    method === 'headings'
      ? buildHeadingTopics(pages, headings, documentId, filename)
      : buildPageTopics(pages, documentId, filename);

  const manualByPage = new Map<number, PreviousManualTopic>();
  for (const previous of previousManualTopics) {
    if (!manualByPage.has(previous.page)) manualByPage.set(previous.page, previous);
  }
  if (manualByPage.size > 0) {
    for (const topic of draft) {
      const page = topic.sourceRefs[0]?.page;
      const previous = page ? manualByPage.get(page) : undefined;
      if (previous) {
        topic.title = previous.title;
        topic.summary = previous.summary;
        topic.keywords = previous.keywords;
        topic.autoGenerated = false;
        topic.manuallyEdited = true;
      }
    }
  }

  return { method, topics: draft };
}

function findNumberedHeadings(pages: ExtractedPage[]): HeadingPosition[] {
  const candidates: HeadingPosition[] = [];
  pages.forEach((page, pageIndex) => {
    page.lines.forEach((line, lineIndex) => {
      const match = line.match(/^(\d{1,2}(?:\.\d{1,2}){0,2})[.)]?\s+(.{2,90})$/);
      if (!match) return;
      const title = match[2].replace(/\s+/g, ' ').trim();
      if (!title || title.length < 3) return;
      if (/[.;:,]$/.test(title)) return;
      if (title.split(' ').length > 14) return;
      candidates.push({ pageIndex, lineIndex, lineSpan: 1, page: page.page, title });
    });
  });

  // Repeated headings are usually a contents slide plus the real section.
  // Prefer the occurrence that has more body text beneath it.
  const byTitle = new Map<string, HeadingPosition>();
  for (const candidate of candidates) {
    const key = candidate.title.toLowerCase().replace(/\s+/g, ' ');
    const existing = byTitle.get(key);
    if (!existing || sectionLength(pages, candidate) > sectionLength(pages, existing)) {
      byTitle.set(key, candidate);
    }
  }
  return [...byTitle.values()].sort(
    (a, b) => a.pageIndex - b.pageIndex || a.lineIndex - b.lineIndex,
  );
}

function sectionLength(pages: ExtractedPage[], heading: HeadingPosition): number {
  const page = pages[heading.pageIndex];
  return page.lines.slice(heading.lineIndex + heading.lineSpan).join(' ').length;
}

/**
 * Slide decks rarely number their headings. The slide title is usually the
 * largest text on the page, so font size is a useful deterministic fallback.
 */
function findFontHeadings(pages: ExtractedPage[]): HeadingPosition[] {
  const candidates: HeadingPosition[] = [];
  for (const [pageIndex, page] of pages.entries()) {
    const lines = page.lineInfo;
    if (!lines || lines.length < 2) continue;
    const bodySize = weightedMedianFontSize(lines);
    if (bodySize <= 0) continue;
    const threshold = bodySize * 1.35;
    const groups: Array<{ start: number; span: number; title: string; size: number }> = [];

    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      if (line.fontSize < threshold || !looksLikeSlideTitle(line.text)) continue;
      let title = line.text;
      let span = 1;
      let size = line.fontSize;
      while (index + span < lines.length) {
        const next = lines[index + span];
        if (next.fontSize < threshold) break;
        if (Math.abs(next.fontSize - size) > 1.5) break;
        if (!looksLikeSlideTitle(next.text)) break;
        if (`${title} ${next.text}`.length > 160) break;
        title = `${title} ${next.text}`;
        span += 1;
      }
      groups.push({ start: index, span, title, size });
      index += span - 1;
    }

    if (groups.length === 0) continue;
    groups.sort((a, b) => b.size - a.size || a.start - b.start);
    const best = groups[0];
    if (candidates.some((candidate) => candidate.pageIndex === pageIndex)) continue;
    candidates.push({
      pageIndex,
      lineIndex: best.start,
      lineSpan: best.span,
      page: page.page,
      title: best.title,
    });
  }

  const byTitle = new Map<string, HeadingPosition>();
  for (const candidate of candidates) {
    if (isCoverPage(pages[candidate.pageIndex], candidate)) continue;
    const key = candidate.title.toLowerCase().replace(/\s+/g, ' ');
    if (!byTitle.has(key)) byTitle.set(key, candidate);
  }
  return [...byTitle.values()].sort(
    (a, b) => a.pageIndex - b.pageIndex || a.lineIndex - b.lineIndex,
  );
}

function isCoverPage(page: ExtractedPage, heading: HeadingPosition): boolean {
  if (page.page !== 1 || page.lines.length > 6) return false;
  const body = page.lines.slice(heading.lineIndex + heading.lineSpan).join(' ').trim();
  if (!body || body.length > 160) return false;
  if (/[•]/.test(body)) return false;
  const sentenceMarks = (body.match(/[.!?]/g) ?? []).length;
  return sentenceMarks <= 1;
}

function weightedMedianFontSize(lines: NonNullable<ExtractedPage['lineInfo']>): number {
  const weights = new Map<number, number>();
  for (const line of lines) {
    if (line.fontSize <= 0) continue;
    const rounded = Math.round(line.fontSize);
    weights.set(rounded, (weights.get(rounded) ?? 0) + Math.max(1, line.text.length));
  }
  let best = 0;
  let bestWeight = 0;
  for (const [size, weight] of weights) {
    if (weight > bestWeight) {
      best = size;
      bestWeight = weight;
    }
  }
  return best;
}

function looksLikeSlideTitle(text: string): boolean {
  if (text.length < 3 || text.length > 120) return false;
  if (!/[a-zA-Z]{2}/.test(text)) return false;
  if (text.split(/\s+/).length > 18) return false;
  if (/^[•·\-–—\d\s/.]+$/.test(text)) return false;
  return true;
}

function buildHeadingTopics(
  pages: ExtractedPage[],
  headings: HeadingPosition[],
  documentId: string,
  filename: string,
): GeneratedTopic[] {
  const topics: GeneratedTopic[] = [];
  headings.forEach((heading, index) => {
    const next = headings[index + 1];
    const section = extractSection(pages, heading, next);
    const fullText = [...section.values()].join('\n').trim();
    const sourceRefs: SourceRef[] = [];
    const sectionPages = [...section.keys()];
    const refPages =
      sectionPages.length > 2 ? [sectionPages[0], sectionPages[sectionPages.length - 1]] : sectionPages;
    for (const pageNumber of refPages) {
      const pageText = section.get(pageNumber) ?? '';
      const quote = quoteFrom(pageText);
      if (quote) {
        sourceRefs.push({ documentId, filename, page: pageNumber, quote });
      }
    }
    if (sourceRefs.length === 0) {
      const fallbackPage = pages[heading.pageIndex];
      sourceRefs.push({
        documentId,
        filename,
        page: fallbackPage.page,
        quote: quoteFrom(fallbackPage.text) || heading.title,
      });
    }
    topics.push({
      title: heading.title,
      summary: summarise(fullText),
      keywords: extractKeywords(`${heading.title} ${fullText}`),
      sourceRefs,
      autoGenerated: true,
      manuallyEdited: false,
      sortOrder: topics.length,
    });
  });

  return topics;
}

function extractSection(
  pages: ExtractedPage[],
  heading: HeadingPosition,
  next: HeadingPosition | undefined,
): Map<number, string> {
  const result = new Map<number, string>();
  const lastPageIndex = next ? next.pageIndex : pages.length - 1;
  for (let pageIndex = heading.pageIndex; pageIndex <= lastPageIndex; pageIndex += 1) {
    const page = pages[pageIndex];
    if (!page) continue;
    let lines = page.lines;
    if (pageIndex === heading.pageIndex) {
      lines = lines.slice(heading.lineIndex + heading.lineSpan);
    }
    if (next && pageIndex === lastPageIndex) {
      lines = lines.slice(0, next.lineIndex);
    }
    const text = lines.join('\n').trim();
    if (text) result.set(page.page, text);
  }
  return result;
}

function buildPageTopics(
  pages: ExtractedPage[],
  documentId: string,
  filename: string,
): GeneratedTopic[] {
  const contentPages = pages.filter((page) => page.text.length >= 20);
  const groups: ExtractedPage[][] = [];
  for (let index = 0; index < contentPages.length; index += 2) {
    groups.push(contentPages.slice(index, index + 2));
  }
  return groups.map((group, index) => {
    const start = group[0].page;
    const end = group[group.length - 1].page;
    const sourceRefs: SourceRef[] = group.map((page) => ({
      documentId,
      filename,
      page: page.page,
      quote: quoteFrom(page.text),
    }));
    const text = group.map((page) => page.text).join('\n');
    return {
      title: start === end ? `Page ${start}` : `Pages ${start}–${end}`,
      summary: summarise(text),
      keywords: extractKeywords(text),
      sourceRefs,
      autoGenerated: true,
      manuallyEdited: false,
      sortOrder: index,
    };
  });
}

function quoteFrom(text: string): string {
  const compact = text.replace(/\s+/g, ' ').trim();
  if (!compact) return '';
  if (compact.length <= 300) return compact;
  const window = compact.slice(0, 300);
  const sentenceEnd = Math.max(window.lastIndexOf('. '), window.lastIndexOf('? '), window.lastIndexOf('! '));
  if (sentenceEnd > 80) return window.slice(0, sentenceEnd + 1).trim();
  return makeExcerpt(compact, 280);
}

function summarise(text: string): string {
  const compact = text.replace(/\s+/g, ' ').trim();
  if (!compact) return '';
  const sentences = compact.split(/(?<=[.!?])\s+/).filter((sentence) => sentence.length > 20);
  const selected: string[] = [];
  let words = 0;
  for (const sentence of sentences) {
    const count = sentence.split(/\s+/).length;
    if (words + count > 48) break;
    selected.push(sentence.trim());
    words += count;
    if (selected.length >= 2) break;
  }
  const summary = selected.join(' ') || makeExcerpt(compact, 240);
  return summary.length > 360 ? makeExcerpt(summary, 360) : summary;
}

export function extractKeywords(text: string, limit = 6): string[] {
  const counts = new Map<string, number>();
  const words = text.toLowerCase().match(/[a-z][a-z0-9-]{2,}/g) ?? [];
  for (const word of words) {
    if (STOP_WORDS.has(word)) continue;
    counts.set(word, (counts.get(word) ?? 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit)
    .map(([word]) => word);
}
